"use client";

import { ChangeEvent, useMemo, useState } from "react";
import Papa from "papaparse";
import { sampleAnnouncements } from "../lib/sample-data";
import { canApprove, countWords, makeId, parseTxt } from "../lib/ticker-utils";
import type { TickerRecord } from "../lib/types";

function createRecord(sourceAnnouncement: string, sourceTitle = ""): TickerRecord {
  return { id: makeId(), sourceTitle, sourceAnnouncement, ticker: "", status: "pending" };
}

export default function Home() {
  const [records, setRecords] = useState<TickerRecord[]>([]);
  const [title, setTitle] = useState("");
  const [source, setSource] = useState("");
  const [inputError, setInputError] = useState("");
  const [notice, setNotice] = useState("");
  const [demoMode, setDemoMode] = useState(false);
  const approvedCount = records.filter((record) => canApprove(record) && record.status === "approved").length;
  const previewTicker = useMemo(() => records.find((record) => record.ticker.trim())?.ticker || "Your approved newsroom ticker will appear here", [records]);

  function addRecord() {
    if (!source.trim()) {
      setInputError("Add the complete announcement before adding it to the queue.");
      return;
    }
    setRecords((current) => [...current, createRecord(source.trim(), title.trim())]);
    setSource(""); setTitle(""); setInputError(""); setNotice("Announcement added to the review queue.");
  }

  function loadSamples() {
    setRecords(sampleAnnouncements.map((sample) => ({ ...sample, id: makeId("sample") })));
    setNotice("Five clearly fictional sample announcements loaded.");
  }

  async function generate(record: TickerRecord) {
    setNotice("");
    setRecords((current) => current.map((item) => item.id === record.id ? { ...item, isGenerating: true, generationError: undefined, status: "draft" } : item));
    if (demoMode) {
      const demoTicker = record.sourceAnnouncement.split(/[.!?]/u)[0].trim().split(/\s+/u).slice(0, 10).join(" ");
      setRecords((current) => current.map((item) => item.id === record.id ? { ...item, ticker: demoTicker, generatedTicker: demoTicker, isGenerating: false, status: "draft" } : item));
      setNotice("Demo output inserted. It was not generated by AI.");
      return;
    }
    try {
      const response = await fetch("/api/generate", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ id: record.id, title: record.sourceTitle, sourceAnnouncement: record.sourceAnnouncement }) });
      const result = await response.json() as { ticker?: string; error?: string };
      if (!response.ok || !result.ticker) throw new Error(result.error || "Generation failed.");
      setRecords((current) => current.map((item) => item.id === record.id ? { ...item, ticker: result.ticker || "", generatedTicker: result.ticker, isGenerating: false, status: "draft" } : item));
    } catch (error) {
      const message = error instanceof Error ? error.message : "Generation failed.";
      setRecords((current) => current.map((item) => item.id === record.id ? { ...item, isGenerating: false, status: "needs_review", generationError: message } : item));
    }
  }

  function updateTicker(id: string, ticker: string) {
    setRecords((current) => current.map((item) => item.id === id ? { ...item, ticker, status: "draft", generationError: undefined } : item));
  }

  function move(id: string, direction: -1 | 1) {
    setRecords((current) => {
      const index = current.findIndex((item) => item.id === id);
      const target = index + direction;
      if (index < 0 || target < 0 || target >= current.length) return current;
      const next = [...current]; [next[index], next[target]] = [next[target], next[index]]; return next;
    });
  }

  function exportApproved() {
    const tickers = records.filter((record) => record.status === "approved" && canApprove(record) && !record.isGenerating).map((record, index) => ({
      id: record.id, order: index + 1, sourceTitle: record.sourceTitle, sourceAnnouncement: record.sourceAnnouncement, ticker: record.ticker, status: "approved" as const
    }));
    if (!tickers.length) { setNotice("No eligible approved tickers to export."); return; }
    const blob = new Blob([JSON.stringify({ version: 1, exportedAt: new Date().toISOString(), tickers }, null, 2)], { type: "application/json;charset=utf-8" });
    const url = URL.createObjectURL(blob); const anchor = document.createElement("a");
    anchor.href = url; anchor.download = "tickerdesk-approved-tickers.json"; anchor.click(); URL.revokeObjectURL(url);
    setNotice(`${tickers.length} approved ticker${tickers.length === 1 ? "" : "s"} exported.`);
  }

  function importFile(event: ChangeEvent<HTMLInputElement>) {
    const file = event.target.files?.[0]; event.target.value = "";
    if (!file) return;
    const extension = file.name.toLowerCase().split(".").pop();
    if (extension !== "txt" && extension !== "csv") { setInputError("Only .txt and .csv files are supported."); return; }
    const reader = new FileReader();
    reader.onload = () => {
      const text = String(reader.result || "");
      const imported: TickerRecord[] = [];
      if (extension === "txt") parseTxt(text).forEach((line) => imported.push(createRecord(line)));
      else {
        const parsed = Papa.parse<Record<string, string>>(text, { header: true, skipEmptyLines: true });
        if (parsed.errors.length) { setInputError(`CSV could not be imported: ${parsed.errors[0].message}`); return; }
        const headers = parsed.meta.fields || [];
        const textColumn = headers.find((header) => ["announcement", "text"].includes(header.trim().toLowerCase()));
        if (!textColumn) { setInputError("CSV needs an announcement or text column."); return; }
        parsed.data.forEach((row) => {
          const announcement = (row[textColumn] || "").trim();
          if (announcement) imported.push(createRecord(announcement, (row[headers.find((header) => header.trim().toLowerCase() === "title") || ""] || "").trim()));
        });
      }
      if (!imported.length) setInputError("The file contains no non-empty announcements.");
      else { setRecords((current) => [...current, ...imported]); setInputError(""); setNotice(`${imported.length} announcement${imported.length === 1 ? "" : "s"} imported.`); }
    };
    reader.onerror = () => setInputError("The file could not be read.");
    reader.readAsText(file, "UTF-8");
  }

  return (
    <main className="shell">
      <header className="topbar">
        <div><div className="brand"><span className="brand-mark">TD</span> TickerDesk</div><div className="subtitle">AI-assisted news ticker production</div></div>
        <div className="header-actions"><span className="status-dot">● <span>Newsroom online</span></span><button className="secondary" onClick={loadSamples}>Load sample announcements</button><span className="count-badge">{approvedCount} approved</span><button className="primary" onClick={exportApproved}>Export approved ({approvedCount})</button></div>
      </header>
      <section className="preview"><div className="preview-label">LIVE BROADCAST PREVIEW <span>Editorial queue</span></div><div className="preview-ticker"><span className="live-dot">●</span>{previewTicker}</div></section>
      <section className="workspace">
        <aside className="input-panel panel">
          <div className="eyebrow">01 / INTAKE</div><h1>വാർത്ത നൽകുക <span>Add news</span></h1>
          <p className="muted">Add a source announcement in Malayalam, English, or a mix of both.</p>
          <label>Optional title<input value={title} onChange={(event) => setTitle(event.target.value)} placeholder="e.g. Weather notice" /></label>
          <label>Source announcement<textarea value={source} onChange={(event) => setSource(event.target.value)} placeholder="Paste the complete announcement here…" rows={8} /></label>
          <button className="primary full" onClick={addRecord}>+ Add announcement</button>
          <div className="divider"><span>OR BULK IMPORT</span></div>
          <label className="file-button secondary full">Choose .TXT or .CSV file<input type="file" accept=".txt,.csv,text/plain,text/csv" onChange={importFile} /></label>
          <p className="help">TXT: one announcement per non-empty line. CSV: headers must include <code>announcement</code> or <code>text</code>, with an optional <code>title</code>.</p>
          <label className="demo-toggle"><input type="checkbox" checked={demoMode} onChange={(event) => setDemoMode(event.target.checked)} /> Demo mode <span>Uses local sample text, not AI</span></label>
          {inputError && <div className="error">{inputError}</div>}
        </aside>
        <section className="queue">
          <div className="queue-heading"><div><div className="eyebrow">02 / EDITORIAL QUEUE</div><h2>Review and refine <span>{records.length} sources</span></h2></div>{notice && <div className="notice">{notice}</div>}</div>
          {!records.length ? <div className="empty panel"><div className="empty-icon">✦</div><h3>Your queue is ready</h3><p>Add an announcement or load the fictional samples to begin production.</p></div> : records.map((record, index) => (
            <article className={`review-card ${record.status}`} key={record.id}>
              <div className="card-top"><span className="position">#{String(index + 1).padStart(2, "0")}</span><span className={`status ${record.status}`}>{record.status.replace("_", " ")}</span><div className="card-actions"><button title="Move up" disabled={index === 0} onClick={() => move(record.id, -1)}>↑</button><button title="Move down" disabled={index === records.length - 1} onClick={() => move(record.id, 1)}>↓</button></div></div>
              {record.sourceTitle && <h3>{record.sourceTitle}</h3>}<div className="source-box"><span className="label">SOURCE</span><p>{record.sourceAnnouncement}</p></div>
              <div className="ticker-edit"><div className="ticker-label"><span>GENERATED TICKER</span><span className={countWords(record.ticker) > 10 ? "over" : ""}>{countWords(record.ticker)}/10 words</span></div><textarea value={record.ticker} onChange={(event) => updateTicker(record.id, event.target.value)} placeholder="Generate a ticker or write one manually…" rows={2} /><div className="card-footer"><div>{record.generationError && <span className="error-inline">{record.generationError}</span>}{record.ticker && countWords(record.ticker) > 10 && <span className="error-inline">Over the 10-word limit.</span>}</div><div className="card-buttons"><button className="secondary" disabled={record.isGenerating} onClick={() => generate(record)}>{record.isGenerating ? "Generating…" : record.generatedTicker ? "Regenerate" : "Generate ticker"}</button><button className="approve" disabled={!canApprove(record)} onClick={() => setRecords((current) => current.map((item) => item.id === record.id ? { ...item, status: "approved" } : item))}>{record.status === "approved" ? "✓ Approved" : "Approve"}</button></div></div></div>
            </article>
          ))}
        </section>
      </section>
    </main>
  );
}
